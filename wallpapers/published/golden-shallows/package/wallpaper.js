// sheet -> art affine that puts sprite joint r on R and t on T (kP: art px per sheet px across the axis; negative mirrors the piece)
function segAffine(r, t, R, T, kP) {
  const lu = Math.hypot(t[0] - r[0], t[1] - r[1]), lU = Math.hypot(T[0] - R[0], T[1] - R[1]);
  const u = [(t[0] - r[0]) / lu, (t[1] - r[1]) / lu], v = [-u[1], u[0]];
  const U = [(T[0] - R[0]) / lU, (T[1] - R[1]) / lU], V = [-U[1], U[0]], kA = lU / lu;
  const a = kA * U[0] * u[0] + kP * V[0] * v[0], c = kA * U[0] * u[1] + kP * V[0] * v[1];
  const b = kA * U[1] * u[0] + kP * V[1] * v[0], d = kA * U[1] * u[1] + kP * V[1] * v[1];
  return [a, b, c, d, R[0] - a * r[0] - c * r[1], R[1] - b * r[0] - d * r[1]];
}
function rigidAffine(k, ang, r, R) {
  const cs = Math.cos(ang) * k, sn = Math.sin(ang) * k;
  return [cs, sn, -sn, cs, R[0] - cs * r[0] + sn * r[1], R[1] - sn * r[0] - cs * r[1]];
}
function ik(H, F, l1, l2, side) {         // knee of a two-segment leg; it always bends the same way (outwards and up), like a real joint
  let dx = F[0] - H[0], dy = F[1] - H[1];
  const d = Math.hypot(dx, dy), dc = clamp(d, Math.abs(l1 - l2) + 1e-3, l1 + l2 - 1e-3);
  dx /= d; dy /= d;
  const a = (l1 * l1 - l2 * l2 + dc * dc) / (2 * dc), h = Math.sqrt(Math.max(0, l1 * l1 - a * a));
  const P = [H[0] + a * dx, H[1] + a * dy], k1 = [P[0] - h * dy, P[1] + h * dx], k2 = [P[0] + h * dy, P[1] - h * dx];
  return { knee: side < 0 ? k1 : k2, foot: [H[0] + dc * dx, H[1] + dc * dy] };   // (picking the higher knee flipped it for a frame or two mid-step)
}
const segLen = n => { const j = PARTS[n][2]; return Math.hypot(j[1][0] - j[0][0], j[1][1] - j[0][1]); };
// The event, tau = seconds since it started: short crab-like darts with pauses. It crawls over the rock, walking up one side and
// down the other (see lively); the body leans with each start and stop, the claws pick at the rock in the pauses, and the wave
// has a dip before it and overshoots a little. (Versions 1 "glide" and 3 "slow walk" stay on ../crab-2d/.)
// A track gives at event time tau: s = travel to the left (art px), stride (art px per gait cycle), hb = body below standing
// (art px), on = standing on top (0-1: how far the crab may stand in front of the silhouette, and its feet with it),
// foot(L) = [x, y] offset of a foot from its plant (climbing, ducking), claws [left, right] (deg beyond rest), lift [left, right]
// (shoulder raise, sheet px), lean (rad, + = top to the right), leanAcc (lean per px/s^2 of acceleration), dx = body shift (art px),
// plantDepth(s) = how far below the top a foot planted at travel s sits (climbing and leaving).
// HID / PEEK (setAct) = below standing: hidden (eyes under the top) / eyes over the top
const backOut = u => { const c = .9; u = clamp(u, 0, 1) - 1; return 1 + (c + 1) * u * u * u + c * u * u; };   // overshoots about 4 %
const bump = (t, t0, d) => Math.sin(Math.PI * clamp((t - t0) / d, 0, 1));
function dartP(u, a) {   // 0-1 travel of one move: a smooth start and stop (a = share of the time spent speeding up), steady between
  u = clamp(u, 0, 1);
  const G = t => t * t * t - t * t * t * t / 2;   // integral of smoothstep
  const P = u < a ? a * G(u / a) : u <= 1 - a ? a / 2 + (u - a) : 1 - 1.5 * a + a / 2 - a * G((1 - u) / a);
  return P / (1 - a);
}
const travel = (tau, moves, st) => moves.reduce((s, [t0, t1, n, a]) => s + n * st * dartP((tau - t0) / (t1 - t0), a), 0);
// It crawls over the rock (the legs move like in the right-to-left walk, with more movement):
// after the peek it walks up the rock's right shoulder sideways to the left, crosses the top, and at the end walks on, down
// behind the left side. Climbing and leaving are part of the walk, so the legs use the same gait the whole time. How deep the
// body is below standing is a function of the distance walked (depth), and each foot is planted at the depth the body reaches
// at the end of that foot's stance: going up it reaches up and pulls, going down it reaches down behind the rock.
// moves[0] is the climb, the last move is the exit; the eyes come up first in two small pulls and look left and right.
const stairs = (t, t0, t1, a, b) => {           // a -> b between t0 and t1 in eased steps, so the body moves in pulls
  if (t <= t0) return a;
  if (t >= t1) return b;
  const u = (t - t0) / (t1 - t0) * Math.abs(b - a), k = Math.floor(u);
  return a + Math.sign(b - a) * (k + smooth(0, 1, u - k));
};
function lively(tau, moves, st, tWave, feeds, dur, deeper = 90) {
  const s = travel(tau, moves, st), tClimb = moves[0][0], tTop = moves[0][1];
  const s1 = moves[0][2] * st, sTop = moves.slice(0, -1).reduce((a, m) => a + m[2], 0) * st, s3 = sTop + moves[moves.length - 1][2] * st;
  // hidden 3 px deeper than version 1: on the rock's sloping sides the tilted body lifted an eye over the edge (at the end it
  // stayed visible until the event ended, then popped away); deeper = sheet px
  const DEEP = HID + deeper * S;
  const depth = x => x < s1 ? PEEK * (1 - smooth(0, s1, x)) : x <= sTop ? 0 : DEEP * smooth(sTop, s3, x);
  const hbBody = tau < tClimb ? DEEP - (DEEP - PEEK) * stairs(tau, 0, .9, 0, 2) / 2 : depth(s);
  // the wave: a dip, up with a small overshoot, two slow waves, down (the first version rotated too far; 140 -> 118 deg, waves 18 -> 14)
  const w0 = tWave, up = ease(tau, w0 + .18, w0 + .6), dn = ease(tau, w0 + 2.27, w0 + 2.77);
  const raise = (-10 * ease(tau, w0, w0 + .18) + 128 * backOut((tau - w0 - .18) / .42) * (tau > w0 + .18)) * (1 - dn);
  const wave = 14 * Math.sin(2 * Math.PI * 1.2 * (tau - w0 - .6)) * ease(tau, w0 + .6, w0 + .75) * (1 - ease(tau, w0 + 2.1, w0 + 2.27));
  // picking at the rock in the pauses: a claw rises and tucks in, about 1 px at 1080p
  let pickL = 0, pickR = 0;
  for (const [t0, side] of feeds) { const b = bump(tau, t0, .45); if (side < 0) pickL += b; else pickR += b; }
  const on = smooth(.55 * s1, s1, s) * (1 - smooth(sTop, sTop + .35 * (s3 - sTop), s));   // standing on top: feet just in front of the silhouette
  return { dur, s, stride: st, on, footIn: on, bob: .2, leanAcc: .00015,
    hb: hbBody - .35 * bump(tau, tTop, .4) - .5 * up * (1 - dn),          // up a little too far after the climb, settles
    lean: .05 * up * (1 - dn),                                              // leans away from the raised claw
    dx: .6 * Math.sin(2 * Math.PI * (tau - .95)) * ease(tau, .9, 1.15) * (1 - ease(tau, 1.75, 2)),   // peeking: a look left and right
    foot: () => [0, tau < tClimb ? hbBody : 0],                             // before the climb the hidden feet go with the body
    plantDepth: tau < tClimb ? () => 0 : depth,
    claws: [raise + wave - 10 * pickL, 10 * pickR], lift: [70 * up * (1 - dn) + 25 * pickL, 25 * pickR] };
}
