function crabPose(tau) {
  const T = crabTrack(tau), Tn = crabTrack(tau + .02), Tp = crabTrack(tau - .02), st = T.stride;
  const X0 = CRAB_X0 + (T.xoff || 0), bx = X0 - DIR * T.s, tilt = tiltAt(bx);   // DIR -1: the same walk, to the right
  const c0 = T.s / st + .05, sp = (Tn.s - T.s) / .02;   // gait phase follows travel, so feet never slide
  const lean = DIR * (T.lean + clamp((Tn.s - 2 * T.s + Tp.s) / .0004 * T.leanAcc, -.06, .06));   // speeding up to the left tips the top right
  const bob = T.bob * clamp(Math.abs(sp) / 14, 0, 1) * (.5 - .5 * Math.cos(4 * Math.PI * c0));
  const B = add(add([bx + DIR * T.dx, ridgeAt(bx)], rot(tilt, [0, -GROUND * S])), [0, T.hb - bob]), bt = tilt + lean;
  const toArt = q => add(B, rot(bt, [q[0] * S, q[1] * S]));
  crabDraws.length = 0;
  const legDraws = [];
  crabJoints = { B, on: T.on, legs: [] };
  for (const L of LEGS) {
    const c = c0 + L.grp * .5, n = Math.floor(c), f = c - n;
    const plant = m => {
      const sm = (m + DUTY / 2 - .05 - L.grp * .5) * st, xm = X0 - DIR * sm, se = sm + DUTY / 2 * st;   // mid and end of this stance
      const fx = xm + (act.home ? L.side * act.home[L.k] : L.home) * S * Math.cos(tiltAt(xm));
      return [fx, ridgeAt(fx) + FOOT_IN * T.footIn + T.plantDepth(se)];   // climbing: planted where the body will be
    };
    let foot = plant(n);
    if (f >= DUTY) {
      const w = smooth(0, 1, (f - DUTY) / (1 - DUTY)), p1 = plant(n + 1);
      foot = [lerp(foot[0], p1[0], w), lerp(foot[1], p1[1], w) - LIFT * Math.sin(Math.PI * w)];
    }
    const fo = T.foot(L); foot[0] += fo[0]; foot[1] += fo[1];
    const hip = toArt(L.hip);
    const jUp = PARTS[L.up][2], jLo = PARTS[L.lo][2];
    const l1 = segLen(L.up) * UP_STRETCH * S, l2 = Math.hypot(jLo[1][0] - jLo[0][0], jLo[1][1] - jLo[0][1]) * S * LO_STRETCH;
    // a foot right under its own hip folds the leg to its minimum length and the knee swings around (darts: the front feet
    // could end a run there, then the body lowered onto them): keep every foot at least 30 % of the leg length out to its side
    const dmin = .3 * (l1 + l2), need = Math.sqrt(Math.max(0, dmin * dmin - (foot[1] - hip[1]) ** 2));
    if (L.side * (foot[0] - hip[0]) < need) foot[0] = hip[0] + L.side * need;
    const { knee, foot: F } = ik(hip, foot, l1, l2, L.side);
    crabJoints.legs.push({ hip, knee, foot: F, want: foot, reach: Math.hypot(foot[0] - hip[0], foot[1] - hip[1]) / (l1 + l2), step: f < DUTY ? n : -1 });   // step: plant index while the foot is down
    const [r, t] = L.side < 0 ? [jUp[1], jUp[0]] : [jUp[0], jUp[1]];
    legDraws.push([L.k, L.lo, segAffine(jLo[0], jLo[1], knee, F, (L.side > 0 ? -1 : 1) * S)]);
    legDraws.push([L.k, L.up, segAffine(r, t, hip, knee, UP_THIN * S)]);
  }
  for (let k = 3; k >= 0; k--) for (const d of legDraws) if (d[0] === k) crabDraws.push([d[1], d[2]]);   // back legs first
  crabDraws.push(['body', rigidAffine(S, bt, BODY_PIV, B)]);
  const deg = Math.PI / 180;   // walking to the right, the right claw leads: the claw moves are mirrored onto it
  const cl = DIR > 0 ? T.claws : [-T.claws[1], -T.claws[0]], li = DIR > 0 ? T.lift : [T.lift[1], T.lift[0]];
  crabDraws.push(['clawR', rigidAffine(S * CLAW_S, bt + (CLAW_REST[1] + cl[1]) * deg, PARTS.clawR[2][0], toArt([CLAW_AT[0], CLAW_AT[1] - li[1]]))]);
  crabDraws.push(['clawL', rigidAffine(S * CLAW_S, bt + (CLAW_REST[0] + cl[0]) * deg, PARTS.clawL[2][0], toArt([-CLAW_AT[0], CLAW_AT[1] - li[0]]))]);
  return T;
}
