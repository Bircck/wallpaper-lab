function resize(force) {
  if (!gl || lost || gl.isContextLost()) return;
  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  let w = Math.round(innerWidth * dpr * settings.quality), h = Math.round(innerHeight * dpr * settings.quality);
  // at most 2560x1440 pixels: the painting is 1672-1920 px wide, so 4K adds cost (3 ms -> 1.7 ms headless) and no detail; CSS scales up
  const cap = Math.min(1, Math.sqrt(2560 * 1440 / Math.max(1, w * h)), gl.getParameter(gl.MAX_TEXTURE_SIZE) / Math.max(w, h, 1));
  w = Math.max(1, Math.floor(w * cap)); h = Math.max(1, Math.floor(h * cap));
  // pass 1 at exactly 1:1 for the part of the painting the screen shows (cover crop), up to the art's own width, so the painting
  // reaches the screen unresampled. It used to be 1672x941 stretched to the screen (soft), then the mask grid's aspect at the art's
  // width: 1920x1081 at 1080p, a drift of up to half a pixel per row in both passes, worst mid-frame, and a floor of 1672 px that
  // beat against any smaller window (the arch otherwise looked like it had a grid pattern)
  const A = imgs.art.width / imgs.art.height, screenA = w / h;
  const fw = Math.max(640, Math.min(screenA > A ? w : Math.round(h * A), imgs.art.width)), fh = Math.round(fw / A);
  const same = canvas.width === w && canvas.height === h && fw === fboW && fh === fboH;
  if (same && !force) return;
  canvas.width = w; canvas.height = h;
  const coverW = Math.min(1, screenA / A), coverH = Math.min(1, A / screenA);
  const exact = Math.abs(fw * coverW - w) < 1 && Math.abs(fh * coverH - h) < 1;   // 1:1: each screen pixel reads one texel of pass 1
  const vw = exact ? w / fw : coverW, vh = exact ? h / fh : coverH;
  const x0 = clamp(FOCUS[0], vw / 2, 1 - vw / 2) - vw / 2, y0 = clamp(FOCUS[1], vh / 2, 1 - vh / 2) - vh / 2;
  view = exact ? [Math.round(x0 * fw) / fw, Math.round(y0 * fh) / fh, vw, vh] : [x0, y0, vw, vh];
  if (fw !== fboW || fh !== fboH) {
    fboW = fw; fboH = fh;
    gl.activeTexture(gl.TEXTURE5); gl.bindTexture(gl.TEXTURE_2D, fboTex);
    gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, fw, fh, 0, gl.RGBA, gl.UNSIGNED_BYTE, null);
    gl.bindFramebuffer(gl.FRAMEBUFFER, fbo);
    gl.framebufferTexture2D(gl.FRAMEBUFFER, gl.COLOR_ATTACHMENT0, gl.TEXTURE_2D, fboTex, 0);
    gl.bindFramebuffer(gl.FRAMEBUFFER, null);
    for (const [k, wrap] of Object.entries(PAINTED)) {
      gl.bindTexture(gl.TEXTURE_2D, tex[k]);
      gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, gl.RGBA, gl.UNSIGNED_BYTE, fitImage(imgs[k], fw, fh, wrap));
    }
  }
  if (ready) draw();
}
// a painted image at w x h if it is bigger than that (a high-quality canvas resample); a layer that wraps in x gets its wrap
// margins first, so the seam where it repeats stays clean
function fitImage(img, w, h, wrap) {
  if (img.width <= w) return img;
  const P = wrap ? 16 : 0, sw = img.width, sh = img.height;
  let src = img;
  if (P) {
    src = document.createElement('canvas'); src.width = sw + 2 * P; src.height = sh;
    const g = src.getContext('2d'); for (const dx of [-sw, 0, sw]) g.drawImage(img, P + dx, 0);
  }
  const k = w / sw, c = document.createElement('canvas'); c.width = w; c.height = h;
  const g = c.getContext('2d'); g.imageSmoothingEnabled = true; g.imageSmoothingQuality = 'high';
  g.drawImage(src, -P * k, 0, src.width * k, h);
  return c;
}
function draw() {
  if (!ready || lost) return;
  const cloudT = time * 0.0011 * LOOK.clouds * settings.clouds;
  for (const [k, i] of Object.entries(UNITS)) { gl.activeTexture(gl.TEXTURE0 + i); gl.bindTexture(gl.TEXTURE_2D, tex[k]); }
  gl.activeTexture(gl.TEXTURE5); gl.bindTexture(gl.TEXTURE_2D, null);
  gl.bindFramebuffer(gl.FRAMEBUFFER, fbo); gl.viewport(0, 0, fboW, fboH);
  gl.useProgram(progSky);
  gl.uniform1f(uSky.time, time); gl.uniform1f(uSky.cloudT, cloudT);
  gl.uniform1fv(uSky.cAng, crownAngles());
  gl.drawArrays(gl.TRIANGLES, 0, 3);
  gl.bindFramebuffer(gl.FRAMEBUFFER, null); gl.viewport(0, 0, canvas.width, canvas.height);
  gl.activeTexture(gl.TEXTURE5); gl.bindTexture(gl.TEXTURE_2D, fboTex);
  gl.useProgram(progMain);
  const U = uMain;
  gl.uniform2f(U.res, canvas.width, canvas.height); gl.uniform4fv(U.view, view); gl.uniform1f(U.time, time); gl.uniform1f(U.cloudT, cloudT);
  const W = settings.waves;   // one slider for every water motion; the fish rings (U.life) follow it too
  gl.uniform1f(U.waves, LOOK.waves * W); gl.uniform1f(U.swell, LOOK.swell * W); gl.uniform1f(U.gusts, LOOK.gusts * W);
  gl.uniform1f(U.ripples, LOOK.ripples * W); gl.uniform1f(U.life, LOOK.life * W);
  gl.uniform1f(U.clarity, settings.seabed); gl.uniform1f(U.cTime, cTime); gl.uniform1f(U.rTime, rTime);
  gl.drawArrays(gl.TRIANGLES, 0, 3); frames++;
  drawCrab();
}
// art px (y down) -> screen uv (y up): the inverse of pass 2's cover mapping, for a screen of aspect a
function screenUV(x, y, a) {
  const aspA = 1672 / 941;
  let u = x / 1672, v = 1 - y / 941;
  if (a > aspA) { const s = aspA / a; v = (v - clamp(FOCUS[1], .5 * s, 1 - .5 * s)) / s + .5; }
  else { const s = a / aspA; u = (u - clamp(FOCUS[0], .5 * s, 1 - .5 * s)) / s + .5; }
  return [u, v];
}
// colour grade of the painted parts towards the boulder they stand on (Codex painted them brighter and redder than the scene)
const CRAB_GRADE = { sat: .65, mul: [.7, .64, .64] };   // picked from 3 grades (look-test): darker, less red, it is backlit
const SHADOW = { a: .32, rx: 330, ry: 70, dx: 60, dy: 40 };   // contact shadow: strength, half size and offset from the body (sheet px; the sun is low on the left)
let crabLast = -1;
function drawCrab() {
  const [tau, an] = crabEvent(); crabLast = tau;
  if (tau < 0) return;
  setAct(an); crabLastAct = an;
  const T = crabPose(tau), G = act.grade || CRAB_GRADE;
  const W = canvas.width, H = canvas.height, a = W / H;
  const mb = crabDraws.find(d => d[0] === 'body')[1], Bx = mb[0] * BODY_PIV[0] + mb[2] * BODY_PIV[1] + mb[4];
  const clip = (x, y) => {                          // art px (y down) -> clip space
    const [u, v] = screenUV(x, y, a);
    return [u * 2 - 1, v * 2 - 1];
  };
  const vb = new Float32Array(crabDraws.length * 24 + 24);
  let o = 0;
  {                                                 // the contact shadow quad first, in art px, tc = -1..1
    const cx = Bx + SHADOW.dx * S, cy = ridgeAt(cx) + SHADOW.dy * S, rx = SHADOW.rx * S, ry = SHADOW.ry * S;
    const cs = [[-1, -1], [1, -1], [1, 1], [-1, 1]].map(([u, v]) => [...clip(cx + u * rx, cy + v * ry), u, v]);
    for (const i of [0, 1, 2, 0, 2, 3]) { vb.set(cs[i], o); o += 4; }
  }
  for (const [name, M] of crabDraws) {
    const [[rx, ry, rw, rh], [ox, oy]] = PARTS[name];
    const cs = [[rx - 1, ry - 1], [rx + rw + 1, ry - 1], [rx + rw + 1, ry + rh + 1], [rx - 1, ry + rh + 1]].map(([ax, ay]) => {
      const qx = ox + (ax - rx) * DOWN, qy = oy + (ay - ry) * DOWN;
      return [...clip(M[0] * qx + M[2] * qy + M[4], M[1] * qx + M[3] * qy + M[5]), ax / ATLAS, 1 - ay / ATLAS];
    });
    for (const i of [0, 1, 2, 0, 2, 3]) { vb.set(cs[i], o); o += 4; }
  }
  gl.useProgram(progCrab);
  gl.uniform2f(uCrab.res, W, H); gl.uniform1f(uCrab.front, T.front); gl.uniform1f(uCrab.occl, 1);
  gl.uniform1f(uCrab.sat, G.sat); gl.uniform3fv(uCrab.grade, G.mul);
  const bx = spot.box;   // grown 2 px; the ridge's own soft edge decides the rest
  gl.uniform4f(uCrab.rockBox, (bx[0] - 2) / 1672, 1 - (bx[3] + 2) / 941, (bx[2] + 2) / 1672, 1 - (bx[1] - 2) / 941);
  gl.bindBuffer(gl.ARRAY_BUFFER, crabBuf); gl.bufferData(gl.ARRAY_BUFFER, vb, gl.DYNAMIC_DRAW);
  gl.vertexAttribPointer(0, 2, gl.FLOAT, false, 16, 0); gl.enableVertexAttribArray(1); gl.vertexAttribPointer(1, 2, gl.FLOAT, false, 16, 8);
  gl.enable(gl.BLEND); gl.blendFunc(gl.ONE, gl.ONE_MINUS_SRC_ALPHA);
  const onTop = T.front / (FOOT_IN + .8);
  if (onTop > 0) { gl.uniform1f(uCrab.shadow, SHADOW.a * onTop); gl.drawArrays(gl.TRIANGLES, 0, 6); }
  gl.uniform1f(uCrab.shadow, 0);
  gl.drawArrays(gl.TRIANGLES, 6, crabDraws.length * 6);
  gl.disable(gl.BLEND); gl.disableVertexAttribArray(1);
  gl.bindBuffer(gl.ARRAY_BUFFER, quadBuf); gl.vertexAttribPointer(0, 2, gl.FLOAT, false, 0, 0);
}
// starts at once and replaces a running one; without an act (front / boulder) it plays the one after the last shown
function playCrab(a) { crabManual = time; crabManualAct = ACTS[a] ? a : nextAct(); if (ready && stopped()) draw(); }
function stopped() { return hostPaused || testMode || document.hidden || lost || !ready; }   // gulls and lanterns always move
function schedule() {
  cancelAnimationFrame(raf); raf = 0; last = 0; acc = 0; pending = 0;
  if (!stopped()) raf = requestAnimationFrame(tick);
}
function advance(dt) { stepCrowns(time, dt); time += dt; cTime += dt * .12 * LOOK.cspeed; rTime += dt * LOOK.rspeed; }
function tick(now) {
  if (stopped()) { raf = 0; return; }
  const dt = last ? Math.min((now - last) / 1000, 0.1) : 0; last = now;
  acc += dt; pending += dt;
  const interval = settings.fps > 0 ? 1 / settings.fps : 0;
  if (acc + 1e-4 >= interval) {
    acc = Math.max(0, acc - interval);
    if (acc > interval) acc = 0;
    advance(pending); pending = 0;
    draw();
  }
  raf = requestAnimationFrame(tick);
}
function fail(err) {
  ready = false; cancelAnimationFrame(raf); canvas.hidden = true;
  document.body.style.backgroundImage = `url('${new URL(FILES.art, here).href}')`;
  console.warn('Animation unavailable, showing still art:', err && err.message);
}
